function grab(src, marker, closer) {
  const start = src.indexOf(marker);
  if (start === -1) throw new Error(`marker not found: ${marker}`);
  const exprStart = start + marker.length;
  const end = src.indexOf(closer, exprStart);
  if (end === -1) throw new Error(`closer not found after: ${marker}`);
  // Re-append the closing bracket (closer is "\n];"-shaped, possibly indented).
  const bracket = closer.trim().slice(0, 1);
  const expr = src.slice(exprStart, end) + "\n" + bracket;
  return vm.runInNewContext("(" + expr + ")", {}, { timeout: 5000 });
}

const ENT = { "&amp;": "&", "&lt;": "<", "&gt;": ">", "&quot;": '"', "&#39;": "'", "&nbsp;": " " };
const decode = (s) => s.replace(/&(amp|lt|gt|quot|#39|nbsp);/g, (m) => ENT[m]);
const stripTags = (s) =>
  decode(s.replace(/<\/span>/g, "</span> ").replace(/<[^>]+>/g, "")).replace(/\s+/g, " ").trim();
const lf = (s) => s.replace(/\r\n/g, "\n");

function tableToMd(html) {
  const rows = [...html.matchAll(/<tr>([\s\S]*?)<\/tr>/g)].map((r) =>
    [...r[1].matchAll(/<t[hd][^>]*>([\s\S]*?)<\/t[hd]>/g)].map((c) => stripTags(c[1])),
  );
  if (!rows.length) return "";
  const md = [];
  md.push("| " + rows[0].join(" | ") + " |");
  md.push("|" + rows[0].map(() => " --- ").join("|") + "|");
  for (const r of rows.slice(1)) md.push("| " + r.join(" | ") + " |");
  return md.join("\n");
}

const preToMd = (html) => "```sql\n" + decode(html.replace(/<[^>]+>/g, "")).trim() + "\n```";

const pad = (n) => String(n).padStart(3, "0");

function writeTs(file, typeName, exportName, data, provenance) {
  const header =
    `// GENERATED by scripts/migration/gen-content.mjs — ${new Date().toISOString().slice(0, 10)}\n` +
    `// Source: ${provenance}\n` +
    `// Do not hand-edit content items: regenerate, or record any manual edit in MIGRATION_NOTES.md.\n` +
    `import type { ${typeName} } from "../../schema";\n\n` +
    `export const ${exportName}: ${typeName}[] = `;
  writeFileSync(file, header + JSON.stringify(data, null, 2) + ";\n", "utf8");
  log(`wrote ${path.relative(process.cwd(), file)} (${data.length} items)`);
}

