function sectionInner(id) {
  const m = html.match(new RegExp(`<section class="(?:domain|panel)" id="${id}">([\\s\\S]*?)</section>`));
  if (!m) throw new Error(`section ${id} not found`);
  return m[1];
}

function domainSectionToMd(inner) {
  const md = [];
  const checklist = [];
  const blockRe = /<h3>([\s\S]*?)<\/h3>|<div class="tbl-scroll">([\s\S]*?<\/table>)<\/div>|<pre>([\s\S]*?)<\/pre>|<div class="trap">([\s\S]*?)<\/div>|<ul class="check"[^>]*>([\s\S]*?)<\/ul>|<p[^>]*>([\s\S]*?)<\/p>/g;
  let m;
  while ((m = blockRe.exec(inner))) {
    if (m[1] !== undefined) md.push(`### ${stripTags(m[1])}`);
    else if (m[2] !== undefined) md.push(tableToMd(m[2]));
    else if (m[3] !== undefined) md.push(preToMd(m[3]));
    else if (m[4] !== undefined) md.push(`> **${stripTags(m[4]).startsWith("Trap:") ? "" : ""}${stripTags(m[4])}**`);
    else if (m[5] !== undefined)
      for (const l of [...m[5].matchAll(/<label[^>]*>([\s\S]*?)<\/label>/g)]) checklist.push(stripTags(l[1]));
    else if (m[6] !== undefined) {
      const t = stripTags(m[6]);
      if (t) md.push(t);
    }
  }
  return { body: md.join("\n\n"), checklist };
}

